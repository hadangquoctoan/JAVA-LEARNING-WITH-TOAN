public class Special_char {
    public static void main(String[] args) {
        String txt = "we are the \"FPT\" guys in Vietnam."; // use \ to tell the Java language that after that \ just see it as normal string
        String txt2 =  "It\'s aright";
        String txt3 = "The character \\ is called backslash";
        
        System.out.println(txt);
        System.out.println(txt2);
        System.out.println(txt3);
        System.out.println("Dòng 1: Xin chào!\nDòng 2: Chúc bạn học tốt Java.");
        System.out.println("ID\tTên môn học\tĐiểm");
        System.out.println("01\tToán học\t9.5");
        System.out.println("02\tLập trình\t10.0");
        System.out.println("Hello!\b?");
    }
    
}
